import { launch, BOOKS, URL0, wait } from './lib.mjs';
const { browser, page, logs } = await launch({ width: 390, height: 780, touch: true, ctx: { isMobile: true } });
await page.goto(URL0);
await page.waitForSelector('.shelf-head');
await page.setInputFiles('input[type=file]', [BOOKS + '/sample.epub']);
await page.waitForFunction(() => document.querySelectorAll('.book').length >= 1, null, { timeout: 30000 });
await page.locator('.book .book-open').first().tap();
await page.waitForSelector('.content p'); await wait(800);
const fs0 = await page.evaluate(() => window.__pyreader.reader.settings.fontSize);
const cdp = await page.context().newCDPSession(page);
const steps = 8;
await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 150, y: 400, id: 1 }, { x: 240, y: 400, id: 2 }] });
for (let i = 1; i <= steps; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 150 - i * 12, y: 400, id: 1 }, { x: 240 + i * 12, y: 400, id: 2 }] });
await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
await wait(700);
const fs1 = await page.evaluate(() => window.__pyreader.reader.settings.fontSize);
console.log(fs1 > fs0 ? 'PASS' : 'FAIL', `pinch-out: font ${fs0} -> ${fs1}`);
await browser.close();
process.exit(fs1 > fs0 ? 0 : 1);
